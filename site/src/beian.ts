/**
 * ICP 备案号的解析与校验。
 *
 * 落地页同一份代码部署到两个域名:`.com`(Cloudflare Pages,境外)与 `.com.cn`
 * (阿里云 ECS,已备案)。差异只有页脚这一条备案号,靠构建期环境变量注入——
 * 国内构建设置它,Pages 那边不设,于是两边代码一字不差。
 *
 * 三种输入三种归宿:
 * - **未设置 / 空串 / 纯空白** → `null`,不渲染。CI 与托管平台常把「没填」传成空串,
 *   把它当非法值会让 `.com` 那侧莫名构建失败。
 * - **合法** → 去掉两端空白后原样返回。
 * - **设置了但格式非法** → 抛错,让构建失败。「可选」不等于「随便写什么都行」:
 *   写错的备案号是违规展示,静默放行等于把违规藏到线上,而线上没人会去看页脚。
 */

/** `<省份简称>ICP备<数字>号`,同主体多站点时带 `-<序号>` 后缀。 */
const ICP_PATTERN = /^[一-龥]{1,2}ICP备\d{4,}号(-\d+)?$/

export function resolveIcpBeian(raw: string | undefined): string | null {
  const value = raw?.trim()
  if (!value) return null
  if (!ICP_PATTERN.test(value)) {
    throw new Error(
      `ICP 备案号格式不合法:${value}。`
        // 这里用明显是占位的示例,不用本站的真实备案号 ——
        // 拿真值当格式示范,读错误信息的人会以为那就是该填进去的值。
        + '期望形如「省份简称 + ICP备 + 数字 + 号」,同主体多站点时带 -序号,例:苏ICP备12345678号-1。'
        + '若本次构建不该带备案号(如境外部署),请不要设置该环境变量,而不是留空或写占位值。',
    )
  }
  return value
}
